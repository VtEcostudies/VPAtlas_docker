-- ── Column type corrections ─────────────────────────────────────────────────

-- visitLocatePool: seven spellings of three states, stored as text --
--   Yes / 1 / true  (836 rows)   -> true
--   No  / 0 / false (1432 rows)  -> false
--   -1 / '' / NULL  (251 rows)   -> NULL, meaning "not recorded"
-- -1 is the Survey123 no-data sentinel and must not become false; a pool nobody
-- tried to find is not a pool that could not be found.
-- Guarded so the migration is safe to re-run: once the column is boolean, the
-- lower() in the USING clause would fail on a boolean argument.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_name = 'vpvisit' AND column_name = 'visitLocatePool'
                 AND data_type = 'text') THEN
        ALTER TABLE vpvisit ALTER COLUMN "visitLocatePool" DROP DEFAULT;
        ALTER TABLE vpvisit ALTER COLUMN "visitLocatePool" TYPE boolean
            USING CASE
                WHEN "visitLocatePool" IS NULL THEN NULL
                WHEN btrim(lower("visitLocatePool")) IN ('1', 'true', 'yes', 't', 'y') THEN true
                WHEN btrim(lower("visitLocatePool")) IN ('0', 'false', 'no', 'f', 'n') THEN false
                ELSE NULL
            END;
    END IF;
END
$$;

COMMENT ON COLUMN vpvisit."visitLocatePool" IS
  'Whether the observer located the pool in the field. NULL means not recorded; the legacy -1 sentinel maps here, not to false.';

-- visitSubmergedVeg: a percent cover measure like its four siblings
-- (visitPoolTrees / Shrubs / Emergents / FloatingVeg, all real 0-100), but
-- stored as integer. One row carries data.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_name = 'vpvisit' AND column_name = 'visitSubmergedVeg'
                 AND data_type = 'integer') THEN
        ALTER TABLE vpvisit ALTER COLUMN "visitSubmergedVeg" TYPE real
            USING "visitSubmergedVeg"::real;
    END IF;
END
$$;

COMMENT ON COLUMN vpvisit."visitSubmergedVeg" IS
  'Percent of the pool occupied by submerged vegetation, 0-100.';

-- visitFishSize: all 2519 rows are NULL, so there is nothing to convert -- only
-- a constraint to add, so the column can hold what it is meant to hold. A CHECK
-- rather than an enum keeps NULL allowed and keeps the vocabulary editable in
-- _helpers/normalize_values.js without a type migration.
ALTER TABLE vpvisit
    DROP CONSTRAINT IF EXISTS vpvisit_visitfishsize_check;
ALTER TABLE vpvisit
    ADD CONSTRAINT vpvisit_visitfishsize_check
    CHECK ("visitFishSize" IS NULL OR "visitFishSize" IN ('Small', 'Medium', 'Large'));

COMMENT ON COLUMN vpvisit."visitFishSize" IS
  'Size class of fish observed: Small, Medium or Large. NULL where not recorded.';

