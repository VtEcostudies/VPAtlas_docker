-- Cleans up three columns whose stored type could not express what they hold,
-- and reconciles the controlled-vocabulary text fields to one spelling each.
--
-- WHY THIS EXISTS
--   These fields are controlled vocabularies in the VPAtlas visit form but plain
--   text in the database, and values arrive from three directions -- the form,
--   the Survey123 sync, and years of legacy imports -- with nothing reconciling
--   them. "Leaf litter" was stored 1074 times, "Leaflitter" 94 times, and once
--   as the JSON-array-shaped string '["Leaf litter"]'.
--
--   That is not cosmetic. survey/visit_create.html restores its checkboxes with
--   an exact string match:
--
--       document.querySelector(`.visitSubstrate[value="${s}"]`)
--
--   so a visit stored as "Leaflitter" opens with no substrate ticked, and
--   re-saving it silently drops the answer. Downstream the same mismatch breaks
--   GIS symbology, definition queries and any group-by.
--
-- THE SAME RULE, THREE PLACES
--   The UPDATE statements below are GENERATED by _schema/build_normalize_sql.js,
--   which reads every DISTINCT value present and resolves it through
--   _helpers/normalize_values.js -- the same module the Survey123 ingest path
--   now calls before writing. Cleanup and prevention are one rule, expressed
--   once. _schema/schema.test.js fails the build if a non-canonical value
--   reappears.
--
-- LEFT ALONE DELIBERATELY
--   visitInletType and visitOutletType each hold one row reading "Yes", which no
--   canonical spelling covers -- "Yes" to what? Rewriting it would be a guess,
--   so both are preserved and reported by the test until someone decides.
--   visitForestUpland holds "Hardwood" (2 rows) alongside "Deciduous" (590).
--   They may well mean the same thing, but that is an ecological judgement and
--   is not made here.
--
-- THE VIEWS ARE DROPPED AND REBUILT
--   ALTER COLUMN TYPE cannot run while a view depends on the column, so the two
--   canonical publication views are dropped up front and recreated at the end
--   from the regenerated definitions. Their column list is unchanged; only the
--   types behind visitLocatePool and visitSubmergedVeg move.
-- =============================================================================

